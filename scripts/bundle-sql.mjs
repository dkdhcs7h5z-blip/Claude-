// Concatenates supabase/migrations/*.sql into supabase/setup.sql — a single file
// that can be pasted into the Supabase SQL editor to set up a new project.
// Run: npm run db:bundle   (a unit test fails if the bundle is out of date)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

export function bundle(dir = 'supabase/migrations') {
  const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
  const header = `-- =============================================================================
-- Women's Health & Reproductive Medicine Intelligence System — database setup
-- GENERATED by scripts/bundle-sql.mjs from supabase/migrations (do not edit).
-- Paste the whole file into Supabase → SQL Editor on a NEW project and run once.
-- =============================================================================
`;
  return header + files.map((f) => `\n-- >>> ${f}\n${readFileSync(join(dir, f), 'utf8').trim()}\n`).join('');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync('supabase/setup.sql', bundle());
  console.log('wrote supabase/setup.sql');
}
